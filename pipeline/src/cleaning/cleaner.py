"""
STEPS 2 & 3 — Data Cleaning + Validation
=========================================
STEP 2 — Keep OHLCV and required audit metadata.
          Extra source columns are removed; quality metadata is generated by this layer.

STEP 3 — Validate:
  - No missing timestamps
  - No NaN values
  - Strictly sorted by time
  - No duplicates
  - No bad candles (H < L, price <= 0)

FAILS loudly on critical validation errors.
"""
import numpy as np
import pandas as pd
from pathlib import Path
from typing import Tuple, Optional

from src.config import CLEANING_CFG, CleaningConfig
from src.utils.logger import get_logger
from src.utils.time_utils import is_fx_session

logger = get_logger("DataCleaner")

REQUIRED_COLS = {"time", "open", "high", "low", "close", "volume"}


class ValidationError(Exception):
    """Raised when data fails critical validation."""
    pass


class DataCleaner:
    """
    Cleans raw 1m OHLCV data:
      1. Column selection (only OHLCV)
      2. Type enforcement
      3. Deduplication
      4. Sorting
      5. Gap detection and filling
      6. Price/volume sanity checks
      7. Weekend/session filtering
    """

    def __init__(self, cfg: CleaningConfig = CLEANING_CFG):
        self.cfg = cfg

    # ─── Main entry point ────────────────────────────────────────────────────

    def clean(
        self,
        df:       pd.DataFrame,
        symbol:   str,
        market:   str,
        timeframe: str = "1m",
    ) -> pd.DataFrame:
        """
        Run full cleaning pipeline on a DataFrame.
        Returns cleaned DataFrame or raises ValidationError.
        """
        original_len = len(df)
        self._last_imputed_times: set[int] = set()
        logger.info(f"[{market}/{symbol}] Cleaning {original_len:,} rows...")

        # ── Step 2: Column selection ──────────────────────────────────────────
        df = self._select_columns(df)

        # ── Step 2: Type enforcement ──────────────────────────────────────────
        df = self._enforce_types(df)

        # ── Audit raw ordering / future timestamps before normalization ─────────
        raw_times = df["time"].to_numpy(copy=True)
        sequence_valid = bool(len(raw_times) < 2 or np.all(np.diff(raw_times) > 0))
        if len(df) and int(df["time"].max()) > int(pd.Timestamp.now(tz='UTC').timestamp() * 1000) + 5_000:
            raise ValidationError(f"[{symbol}] Future timestamps detected")

        # ── Step 3: Deduplication ─────────────────────────────────────────────
        before = len(df)
        duplicate_times = df["time"].duplicated(keep='first')
        df = df.drop_duplicates(subset=["time"]).reset_index(drop=True)
        if len(df) < before:
            logger.info(f"  Removed {before - len(df):,} duplicate rows")

        # ── Step 3: Sort by time ──────────────────────────────────────────────
        df = df.sort_values("time").reset_index(drop=True)

        # ── Step 3: Sanity checks (fail-fast) ────────────────────────────────
        self._validate_prices(df, symbol)

        # ── Step 3: Gap detection + filling ──────────────────────────────────
        df, gaps = self._fill_gaps(df, timeframe)
        if gaps > 0:
            logger.info(f"  Filled {gaps:,} missing timestamps")

        # ── Required audit metadata ──────────────────────────────────────────
        # Imputed rows are explicitly marked and must never become live signals.
        imputed_times = set(getattr(self, '_last_imputed_times', set()))
        df['source'] = market
        df['is_imputed'] = df['time'].isin(imputed_times)
        df['is_synthetic'] = False
        df['sequence_valid'] = sequence_valid
        df['latency'] = int(pd.Timestamp.now(tz='UTC').timestamp() * 1000) - df['time']
        df['quality'] = np.where(df['is_imputed'], 'imputed', np.where(sequence_valid, 'good', 'invalid'))

        # ── Step 3: Remove NaN ────────────────────────────────────────────────
        nan_count = df.isnull().sum().sum()
        if nan_count > 0:
            logger.warning(f"  Dropping {nan_count} NaN values")
            df = df.dropna().reset_index(drop=True)

        # ── Weekend / session filter ──────────────────────────────────────────
        if self.cfg.skip_weekends and market == "mt5":
            df = self._filter_sessions(df)

        # ── Final validation ──────────────────────────────────────────────────
        self._final_validate(df, symbol)

        removed = original_len - len(df)
        logger.info(
            f"[{market}/{symbol}] Clean complete: "
            f"{len(df):,} rows (removed {removed:,})"
        )
        return df

    # ─── Column selection (STEP 2) ───────────────────────────────────────────

    def _select_columns(self, df: pd.DataFrame) -> pd.DataFrame:
        """Keep ONLY time, open, high, low, close, volume."""
        missing = REQUIRED_COLS - set(df.columns)
        if missing:
            raise ValidationError(f"Missing required columns: {missing}")

        extra = set(df.columns) - REQUIRED_COLS
        if extra:
            logger.debug(f"  Dropping extra columns: {extra}")

        return df[list(REQUIRED_COLS)][["time", "open", "high", "low", "close", "volume"]]

    # ─── Type enforcement ────────────────────────────────────────────────────

    def _enforce_types(self, df: pd.DataFrame) -> pd.DataFrame:
        df = df.copy()
        df["time"]   = pd.to_numeric(df["time"],   errors="coerce").astype("int64")
        df["open"]   = pd.to_numeric(df["open"],   errors="coerce").astype("float64")
        df["high"]   = pd.to_numeric(df["high"],   errors="coerce").astype("float64")
        df["low"]    = pd.to_numeric(df["low"],    errors="coerce").astype("float64")
        df["close"]  = pd.to_numeric(df["close"],  errors="coerce").astype("float64")
        df["volume"] = pd.to_numeric(df["volume"], errors="coerce").astype("float64")
        return df

    # ─── Price validation (STEP 3 — fail-fast) ───────────────────────────────

    def _validate_prices(self, df: pd.DataFrame, symbol: str) -> None:
        """FAIL if data has critical inconsistencies."""
        n = len(df)
        if n < 10:
            raise ValidationError(f"[{symbol}] Only {n} rows — insufficient data")

        # High must be >= Low
        bad_hl = (df["high"] < df["low"]).sum()
        if bad_hl > 0:
            raise ValidationError(f"[{symbol}] {bad_hl:,} candles where High < Low")

        # No zero or negative prices
        bad_prices = ((df[["open", "high", "low", "close"]] <= 0).any(axis=1)).sum()
        if bad_prices > n * 0.01:  # tolerate < 1%
            raise ValidationError(
                f"[{symbol}] {bad_prices:,} candles with zero/negative prices "
                f"({bad_prices/n:.1%}) — data quality too low"
            )
        elif bad_prices > 0:
            logger.warning(f"  [{symbol}] {bad_prices} zero-price candles (removing)")
            df.drop(df[(df[["open","high","low","close"]] <= 0).any(axis=1)].index, inplace=True)

        # High must be >= Open, Close
        bad_high = ((df["high"] < df["open"]) | (df["high"] < df["close"])).sum()
        bad_low  = ((df["low"]  > df["open"]) | (df["low"]  > df["close"])).sum()
        if bad_high + bad_low > n * 0.001:
            raise ValidationError(
                f"[{symbol}] Too many OHLC violations: "
                f"high<open/close={bad_high}, low>open/close={bad_low}"
            )

    # ─── Gap filling (STEP 3) ─────────────────────────────────────────────────

    def _fill_gaps(self, df: pd.DataFrame, timeframe: str = "1m") -> Tuple[pd.DataFrame, int]:
        """
        Detect missing timestamps and fill using forward-fill.
        Only fills gaps up to cfg.max_gap_minutes.
        Larger gaps are left as-is (weekend, maintenance).
        """
        freq_ms = self._tf_to_ms(timeframe)
        if freq_ms == 0:
            return df, 0

        # Build expected complete timestamp range
        times = df["time"].values
        if len(times) < 2:
            return df, 0

        expected = np.arange(times[0], times[-1] + freq_ms, freq_ms, dtype="int64")
        actual_set = set(times.tolist())
        missing_ts = [t for t in expected if t not in actual_set]

        if not missing_ts:
            return df, 0

        # Only fill small gaps
        max_gap_ms = self.cfg.max_gap_minutes * 60_000
        small_gaps = []
        for i, ts in enumerate(missing_ts):
            # Find previous candle
            prev_ts = ts - freq_ms
            if prev_ts in actual_set:
                # Check gap size (consecutive missing = large gap)
                gap_size = 1
                while ts + gap_size * freq_ms in [t for t in missing_ts if t > ts]:
                    gap_size += 1
                if gap_size * freq_ms <= max_gap_ms:
                    small_gaps.append(ts)

        if not small_gaps:
            logger.warning(
                f"  {len(missing_ts):,} missing timestamps but all are large gaps "
                f"(weekend/maintenance) — not filling"
            )
            return df, 0

        # Forward-fill small gaps
        prev_rows = []
        for ts in small_gaps:
            prev_ts = ts - freq_ms
            prev_row = df[df["time"] == prev_ts]
            if not prev_row.empty:
                new_row = prev_row.copy()
                new_row["time"] = ts
                self._last_imputed_times.add(int(ts))
                prev_rows.append(new_row)

        if prev_rows:
            fill_df = pd.concat(prev_rows, ignore_index=True)
            df = pd.concat([df, fill_df], ignore_index=True)
            df = df.sort_values("time").reset_index(drop=True)

        return df, len(small_gaps)

    # ─── Session filter (STEP 2 — remove weekend/low-liquidity) ─────────────

    def _filter_sessions(self, df: pd.DataFrame) -> pd.DataFrame:
        """Remove weekend and low-liquidity candles for FX."""
        dts = pd.to_datetime(df["time"], unit="ms", utc=True)

        # Remove weekends
        mask = dts.dt.dayofweek < 5  # Mon=0, Fri=4
        before = len(df)
        df = df[mask].reset_index(drop=True)
        logger.debug(f"  Session filter removed {before - len(df):,} weekend rows")

        return df

    # ─── Final validation (STEP 3) ────────────────────────────────────────────

    def _final_validate(self, df: pd.DataFrame, symbol: str) -> None:
        """Final checks after cleaning."""
        if df.isnull().any().any():
            raise ValidationError(f"[{symbol}] NaN values remain after cleaning")

        if not df["time"].is_monotonic_increasing or (len(df) > 1 and not (df['time'].diff().dropna() > 0).all()):
            raise ValidationError(f"[{symbol}] Time is not strictly sorted")
        if (df['latency'] < -5_000).any():
            raise ValidationError(f"[{symbol}] Future latency detected")
        if not set(['source','quality','is_imputed','is_synthetic','latency','sequence_valid']).issubset(df.columns):
            raise ValidationError(f"[{symbol}] Required data-quality metadata missing")

        dups = df["time"].duplicated().sum()
        if dups > 0:
            raise ValidationError(f"[{symbol}] {dups:,} duplicate timestamps remain")

        logger.debug(f"  [{symbol}] Validation passed ✓")

    # ─── Helpers ──────────────────────────────────────────────────────────────

    @staticmethod
    def _tf_to_ms(tf: str) -> int:
        mapping = {
            "1m": 60_000, "5m": 300_000, "15m": 900_000,
            "30m": 1_800_000, "1h": 3_600_000, "4h": 14_400_000,
            "1d": 86_400_000,
        }
        return mapping.get(tf, 60_000)

    def stats(self, df: pd.DataFrame) -> dict:
        """Return quality statistics for logging."""
        n = len(df)
        return {
            "rows":        n,
            "from":        pd.Timestamp(df["time"].iloc[0],  unit="ms").isoformat(),
            "to":          pd.Timestamp(df["time"].iloc[-1], unit="ms").isoformat(),
            "nan_pct":     df.isnull().mean().mean(),
            "zero_volume": (df["volume"] == 0).sum(),
            "avg_hl_pct":  ((df["high"] - df["low"]) / df["close"]).mean(),
        }
